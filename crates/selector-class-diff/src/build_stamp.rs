//! Exact delta for one reviewed sbt-buildinfo class layout. This describes the
//! physically changed literals and their generated accessors, not suite
//! reachability or permission to ignore generated sources.
use super::Reader;
use selector_types::ContentHash;
use sha2::{Digest, Sha256};

const MAX_CLASS_BYTES: usize = 16 * 1024;
const MODULE_TEMPLATE: &str = "a99cf2c03bc4ed95946f09b2bb44071658c901c7a9768e63bbde543f38458ba8";
const FORWARDER: &str = "405102b569db87b93918cc577aab8e69b08ec7c0da53aeb24e04ce0aa69a46a5";
pub const OWNER: &str = "org/lfdecentralizedtrust/splice/environment/BuildInfo$";
pub const DESCRIPTOR: &str = "()Ljava/lang/String;";

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Unsupported {
    ClassSize,
    ModuleTemplate,
    ForwarderTemplate,
    StampLiteral,
    SourceTemplate,
}

/// The source version or timestamp can change independently. `toString` reads
/// a third field whose initializer formats both values. It is therefore
/// included in the observation surface if either input changes.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ReaderSurface {
    CompiledVersion,
    CommitUnixTimestamp,
    FormattedSummary,
}

impl ReaderSurface {
    pub const fn member(self) -> &'static str {
        match self {
            Self::CompiledVersion => "compiledVersion",
            Self::CommitUnixTimestamp => "commitUnixTimestamp",
            Self::FormattedSummary => "toString",
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Stamp<'a> {
    pub compiled_version: &'a str,
    pub commit_unix_timestamp: &'a str,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct BuildStampDelta<'a> {
    pub before: Stamp<'a>,
    pub after: Stamp<'a>,
    pub before_module: ContentHash,
    pub after_module: ContentHash,
    pub forwarder: ContentHash,
}

impl BuildStampDelta<'_> {
    pub fn reader_surfaces(&self) -> impl Iterator<Item = ReaderSurface> {
        let version = self.before.compiled_version != self.after.compiled_version;
        let timestamp = self.before.commit_unix_timestamp != self.after.commit_unix_timestamp;
        [
            version.then_some(ReaderSurface::CompiledVersion),
            timestamp.then_some(ReaderSurface::CommitUnixTimestamp),
            (version || timestamp).then_some(ReaderSurface::FormattedSummary),
        ]
        .into_iter()
        .flatten()
    }

    /// Verify that the corresponding captured generated source files contain
    /// only the literals read from their admitted compiled classes.
    pub fn verify_sources(
        &self,
        before: &[u8],
        after: &[u8],
    ) -> Result<[ContentHash; 2], Unsupported> {
        for (source, stamp) in [(before, self.before), (after, self.after)] {
            let expected = format!(
                r#"// $COVERAGE-OFF$
package org.lfdecentralizedtrust.splice.environment

/** This object was generated by sbt-buildinfo. */
case object BuildInfo {{
  /** The value is "{version}". */
  val compiledVersion: String = "{version}"
  /** The value is "{timestamp}". */
  val commitUnixTimestamp: String = "{timestamp}"
  /** The value is "0.9.1". */
  val compatibleVersion: String = "0.9.1"
  override val toString: String = {{
    "compiledVersion: %s, commitUnixTimestamp: %s, compatibleVersion: %s".format(
      compiledVersion, commitUnixTimestamp, compatibleVersion
    )
  }}
}}
// $COVERAGE-ON$
"#,
                version = stamp.compiled_version,
                timestamp = stamp.commit_unix_timestamp,
            );
            if source != expected.as_bytes() {
                return Err(Unsupported::SourceTemplate);
            }
        }
        Ok([hash(before), hash(after)])
    }
}

fn hash(bytes: &[u8]) -> ContentHash {
    ContentHash(Sha256::digest(bytes).into())
}

/// `MODULE_TEMPLATE` hashes every class byte except the length and bytes of
/// two `CONSTANT_Utf8` entries, whose original tag and position remain fixed.
/// The approved bytecode has these exact loads in `<clinit>`:
///
/// - PC 16 `ldc #29` -> UTF8 #28; PC 18 `putstatic #31` -> compiledVersion.
/// - PC 21 `ldc #33` -> UTF8 #32; PC 23 `putstatic #35` -> commitUnixTimestamp.
///
/// Both fields and `toString` are private static final Strings, read by exact
/// `getstatic; areturn` methods. `toString` is initialized by formatting both
/// stamps and the unchanged `compatibleVersion` value. The two strings have
/// no other references in the reviewed template. The companion forwarder is
/// raw-byte pinned. Changing any other byte requires separate review.
///
/// The result deliberately supplies no negative evidence: class initialization,
/// reflection, resource reads, serialization, logs, and effects in consumers
/// still require the normal provider and execution model.
pub fn compare<'a>(
    before_module: &'a [u8],
    after_module: &'a [u8],
    before_forwarder: &[u8],
    after_forwarder: &[u8],
) -> Result<BuildStampDelta<'a>, Unsupported> {
    if [
        before_module,
        after_module,
        before_forwarder,
        after_forwarder,
    ]
    .iter()
    .any(|bytes| bytes.len() > MAX_CLASS_BYTES)
    {
        return Err(Unsupported::ClassSize);
    }
    let forwarder = hash(before_forwarder);
    if before_forwarder != after_forwarder || forwarder != ContentHash::from_hex(FORWARDER).unwrap()
    {
        return Err(Unsupported::ForwarderTemplate);
    }
    Ok(BuildStampDelta {
        before: stamp(before_module)?,
        after: stamp(after_module)?,
        before_module: hash(before_module),
        after_module: hash(after_module),
        forwarder,
    })
}

fn stamp(bytes: &[u8]) -> Result<Stamp<'_>, Unsupported> {
    let mut reader = Reader::new(bytes);
    reader.take(8).map_err(|_| Unsupported::ModuleTemplate)?;
    let count = reader.u2().map_err(|_| Unsupported::ModuleTemplate)? as usize;
    let mut digest = Sha256::new();
    digest.update(&bytes[..reader.at]);
    let mut slots = [None; 2];
    let mut index = 1;
    let mut unmasked_start = reader.at;
    while index < count {
        let start = reader.at;
        let tag = reader.u1().map_err(|_| Unsupported::ModuleTemplate)?;
        let len = match tag {
            1 => reader.u2().map_err(|_| Unsupported::ModuleTemplate)? as usize,
            3 | 4 | 9..=12 | 17 | 18 => 4,
            5 | 6 => 8,
            7 | 8 | 16 | 19 | 20 => 2,
            15 => 3,
            _ => return Err(Unsupported::ModuleTemplate),
        };
        let data = reader.take(len).map_err(|_| Unsupported::ModuleTemplate)?;
        if let Some(slot) = match index {
            28 => Some(0),
            32 => Some(1),
            _ => None,
        } {
            if tag != 1 {
                return Err(Unsupported::ModuleTemplate);
            }
            slots[slot] = Some(data);
            digest.update(&bytes[unmasked_start..start]);
            digest.update([1, 0, 0]); // retain tag and zero the encoded length
            unmasked_start = reader.at;
        }
        index += if matches!(tag, 5 | 6) { 2 } else { 1 };
    }
    digest.update(&bytes[unmasked_start..]);
    if ContentHash(digest.finalize().into()) != ContentHash::from_hex(MODULE_TEMPLATE).unwrap() {
        return Err(Unsupported::ModuleTemplate);
    }
    let [Some(version), Some(timestamp)] = slots else {
        return Err(Unsupported::ModuleTemplate);
    };
    if !(1..=128).contains(&version.len())
        || !version.first().is_some_and(u8::is_ascii_digit)
        || !version
            .iter()
            .all(|b| b.is_ascii_alphanumeric() || b".-_+".contains(b))
        || !timestamp.iter().all(u8::is_ascii_digit)
    {
        return Err(Unsupported::StampLiteral);
    }
    let compiled_version = std::str::from_utf8(version).map_err(|_| Unsupported::StampLiteral)?;
    let commit_unix_timestamp =
        std::str::from_utf8(timestamp).map_err(|_| Unsupported::StampLiteral)?;
    if commit_unix_timestamp.parse::<i64>().is_err() {
        return Err(Unsupported::StampLiteral);
    }
    Ok(Stamp {
        compiled_version,
        commit_unix_timestamp,
    })
}

