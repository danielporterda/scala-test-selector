//! Complete runtime adapter wiring over explicit compiler facts. Genuine compiler
//! capture integration is exercised by selector-acceptance's independent corpus.
use selector_facts::{FactBuilder, FactSnapshot, FileRecord, OccurrenceRecord, RelationRecord};
use selector_models::runtime::{self, RuntimeInputs, RuntimeSource};
use selector_types::*;
use sha2::{Digest, Sha256};

fn file(builder: &mut FactBuilder, path: &str, source: &str) -> FileId {
    let id = FileId(builder.facts.files.len() as u32);
    let path = builder.intern(path).unwrap();
    let source_id = builder.intern(source).unwrap();
    let context = builder.intern("project:wallet/compile").unwrap();
    builder.facts.files.push(FileRecord {
        path,
        source: source_id,
        revision: StrId::NONE,
        context,
        source_hash: ContentHash(Sha256::digest(source.as_bytes()).into()),
        flags: SOURCE_VERIFIED,
    });
    id
}
fn symbol(
    builder: &mut FactBuilder,
    name: &str,
    display: &str,
    owner: SymbolId,
    file: FileId,
    kind: u32,
    properties: u64,
) -> SymbolId {
    let id = builder.ensure_symbol(name, file).unwrap();
    let display = builder.intern(display).unwrap();
    let record = &mut builder.facts.symbols[id.index()];
    record.display = display;
    record.owner = owner;
    record.file = file;
    record.kind = kind;
    record.properties = properties;
    record.flags = SYMBOL_DEFINED;
    id
}
struct Fixture {
    facts: FactSnapshot,
    client: SymbolId,
    implementation: SymbolId,
    router: FileId,
}
fn fixture(package: &str, stem: &str, literal: &str) -> Fixture {
    let mut builder = FactBuilder::new();
    let client_file = file(
        &mut builder,
        "apps/wallet/target/scala-2.13/src_managed/main/Client.scala",
        "// This file was generated by guardrail\nclass Client",
    );
    let text = format!(
        "// This file was generated by guardrail\ntrait {stem}Handler[E] {{\n  def acceptOffer(): Unit\n}}\nobject {stem}Resource {{\n  def routes[E](handler: {stem}Handler[E], customExtract: String => Directive1[E]): Route = {{\n    {{\n      path(\"offer\")(post(customExtract(\"{literal}\").apply(extracted => complete(handler.acceptOffer()))))\n    }}\n  }}\n}}\n"
    );
    let router = file(
        &mut builder,
        "apps/wallet/target/scala-2.13/src_managed/main/Routes.scala",
        &text,
    );
    let concrete_file = file(
        &mut builder,
        "apps/wallet/src/main/scala/Concrete.scala",
        "class ConcreteHandler",
    );
    let package = package.replace('.', "/");
    let owner = symbol(
        &mut builder,
        &format!("{package}/{stem}Client#"),
        &format!("{stem}Client"),
        SymbolId::NONE,
        client_file,
        13,
        0,
    );
    let client = symbol(
        &mut builder,
        &format!("{package}/{stem}Client#acceptOffer()."),
        "acceptOffer",
        owner,
        client_file,
        3,
        0,
    );
    let owner = symbol(
        &mut builder,
        &format!("{package}/{stem}Handler#"),
        &format!("{stem}Handler"),
        SymbolId::NONE,
        router,
        14,
        0,
    );
    let handler = symbol(
        &mut builder,
        &format!("{package}/{stem}Handler#acceptOffer()."),
        "acceptOffer",
        owner,
        router,
        3,
        4,
    );
    let owner = symbol(
        &mut builder,
        &format!("{package}/{stem}Resource."),
        &format!("{stem}Resource"),
        SymbolId::NONE,
        router,
        10,
        0,
    );
    let routes = symbol(
        &mut builder,
        &format!("{package}/{stem}Resource.routes()."),
        "routes",
        owner,
        router,
        3,
        0,
    );
    let owner = symbol(
        &mut builder,
        "example/ConcreteHandler#",
        "ConcreteHandler",
        SymbolId::NONE,
        concrete_file,
        13,
        0,
    );
    let implementation = symbol(
        &mut builder,
        "example/ConcreteHandler#acceptOffer().",
        "acceptOffer",
        owner,
        concrete_file,
        3,
        0,
    );
    builder.facts.relations.push(RelationRecord {
        source: implementation,
        target: handler,
        kind: RelationKind::Override,
        file: concrete_file,
    });
    let at = text.find("routes[E]").unwrap();
    builder.facts.occurrences.push(OccurrenceRecord {
        file: router,
        symbol: routes,
        span: Span::new(at, at + 6).unwrap(),
        role: 2,
        ordinal: 0,
    });
    let at = text.find("handler.acceptOffer").unwrap() + "handler.".len();
    builder.facts.occurrences.push(OccurrenceRecord {
        file: router,
        symbol: handler,
        span: Span::new(at, at + 11).unwrap(),
        role: 1,
        ordinal: 1,
    });
    Fixture {
        facts: builder.facts,
        client,
        implementation,
        router,
    }
}
#[test]
fn finite_default_generator_pair_emits_compiler_bridge_and_scoped_certificate() {
    let fixture = fixture("example.http.v0", "", "acceptOffer");
    let schema = "openapi: 3.0.3\npaths:\n  /offer:\n    post:\n      operationId: acceptOffer\n      responses: {'200': {description: ok}}\n";
    let build = r#"Compile / guardrailTasks := List(ScalaClient(new File("apps/wallet/src/main/openapi/wallet.yaml"), pkg = "example.http.v0"), ScalaServer(new File("apps/wallet/src/main/openapi/wallet.yaml"), pkg = "example.http.v0"))"#;
    let inputs = RuntimeInputs {
        sources: vec![
            RuntimeSource {
                path: "apps/wallet/src/main/openapi/wallet.yaml",
                text: schema,
            },
            RuntimeSource {
                path: "build.sbt",
                text: build,
            },
        ],
        compiler_inventory_complete: true,
        ..RuntimeInputs::default()
    };
    let nodes: Vec<_> = (0..fixture.facts.symbols.len())
        .map(|index| NodeId(index as u32))
        .collect();
    let out = runtime::contribute(&fixture.facts, &nodes, &inputs).unwrap();
    assert!(
        out.model
            .edges
            .iter()
            .any(|edge| edge.kind == EdgeKind::RuntimeBridge
                && edge.source == nodes[fixture.client.index()]
                && edge.target == nodes[fixture.implementation.index()])
    );
    let binding = out
        .http_bindings
        .iter()
        .find(|binding| binding.path == "/offer")
        .unwrap();
    assert!(binding.scope_complete);
    assert!(binding.guard_files.contains(&fixture.router));
    assert!(binding.symbols.contains(&fixture.implementation));
}
#[test]
fn compiler_renamed_generated_operation_requires_complete_inventory_and_wire_reference() {
    let fixture = fixture("example.http.v0.wallet", "Wallet", "AcceptOffer");
    let schema = "openapi: 3.0.3\npaths:\n  /offer:\n    post:\n      operationId: AcceptOffer\n      tags: [wallet]\n      x-jvm-package: wallet\n      responses: {'200': {description: ok}}\n";
    let nodes: Vec<_> = (0..fixture.facts.symbols.len())
        .map(|index| NodeId(index as u32))
        .collect();
    let mut inputs = RuntimeInputs {
        sources: vec![RuntimeSource {
            path: "apps/wallet/src/main/openapi/wallet.yaml",
            text: schema,
        }],
        generator_packages: vec!["example.http.v0"],
        compiler_inventory_complete: true,
        ..RuntimeInputs::default()
    };
    let out = runtime::contribute(&fixture.facts, &nodes, &inputs).unwrap();
    assert!(
        out.model
            .edges
            .iter()
            .any(|edge| edge.kind == EdgeKind::RuntimeBridge
                && edge.source == nodes[fixture.client.index()]
                && edge.target == nodes[fixture.implementation.index()])
    );
    assert!(out.http_bindings[0].scope_complete);
    inputs.compiler_inventory_complete = false;
    let out = runtime::contribute(&fixture.facts, &nodes, &inputs).unwrap();
    assert!(
        !out.model
            .edges
            .iter()
            .any(|edge| edge.kind == EdgeKind::RuntimeBridge)
    );
    assert!(
        out.http_bindings
            .iter()
            .all(|binding| !binding.scope_complete)
    );
}
